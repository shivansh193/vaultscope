"""Build the Stage 4b training table: feature vectors + traffic-class labels.

Real path: for each ``data/labels/*.json`` whose pcap our Stage 1/3 code can
read, extract a Stage 3 feature vector and pair it with the ground-truth
``traffic_class``.

Bootstrap path: synthesise per-class flows (``_synthetic``) and run them through
the same ``core.flow.feature_vector``. Used until the Stage 0 pcap dataset
exists; every row is marked so no consumer mistakes it for captured data.
"""

from __future__ import annotations

import json
from pathlib import Path

from core.flow import extract_features_by_flow, feature_vector
from core.flow.features import FEATURE_NAMES

from ._synthetic import TRAFFIC_CLASSES, synth_flow

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
LABELS_DIR = REPO_ROOT / "data" / "labels"
PCAPS_DIR = REPO_ROOT / "data" / "pcaps"

FeatureRow = dict[str, float]


# Classes that genuinely look alike on aggregate flow stats. The spec predicts
# "VoIP, ICMP easy; Video vs Web hardest" -- a fraction of each class's flows is
# generated by a confusable sibling (true label kept) so the bootstrap model,
# and its confusion matrix, reflect that instead of a fake 1.0.
_CONFUSABLE: dict[str, tuple[str, ...]] = {
    "Video": ("Web",),
    "Web": ("Video", "Email"),
    "Email": ("Web",),
    "Chat": ("VoIP", "Web"),
    "VoIP": ("Chat",),
    "ICMP": ("VoIP",),
}


def synthetic_table(
    n_per_class: int = 240, *, seed: int = 0, p_confuse: float = 0.16
) -> tuple[list[FeatureRow], list[str]]:
    """``n_per_class`` noisy synthetic flows per class -> (X rows, y labels).

    ``p_confuse`` of each class's flows are shaped like a confusable sibling
    (keeping the true label) and some flows are short, so the aggregate
    features overlap the way captured traffic does.
    """
    import random

    rng = random.Random(seed)
    x: list[FeatureRow] = []
    y: list[str] = []
    for ci, cls in enumerate(TRAFFIC_CLASSES):
        for k in range(n_per_class):
            gen_cls = cls
            if rng.random() < p_confuse and cls in _CONFUSABLE:
                gen_cls = rng.choice(_CONFUSABLE[cls])
            secs = rng.choice((None, None, rng.uniform(3.0, 10.0)))  # 1/3 short flows
            flow = synth_flow(gen_cls, seconds=secs, seed=seed * 100_000 + ci * 1_000 + k)
            x.append(feature_vector(flow))
            y.append(cls)
    return x, y


def pcap_table(
    labels_dir: Path = LABELS_DIR, pcaps_dir: Path = PCAPS_DIR
) -> tuple[list[FeatureRow], list[str]]:
    """Feature rows from the captured dataset. Empty until Stage 0 has run."""
    x: list[FeatureRow] = []
    y: list[str] = []
    for label_path in sorted(labels_dir.glob("*.json")):
        label = json.loads(label_path.read_text())
        cls = label.get("traffic_class")
        if cls not in TRAFFIC_CLASSES:
            continue
        pcap = pcaps_dir / f"{label_path.stem}.pcap"
        if not pcap.exists():
            continue
        flows = extract_features_by_flow(str(pcap))
        # the largest ESP flow in the capture is the injected traffic
        best = max(
            (fv for fv in flows.values() if fv["pkt_total"] > 0),
            key=lambda fv: fv["pkt_total"],
            default=None,
        )
        if best is not None:
            x.append(best)
            y.append(cls)
    return x, y


def load_table(
    *, synthetic: bool | None = None, n_per_class: int = 150, seed: int = 0
) -> tuple[list[FeatureRow], list[str], str]:
    """Return (X, y, source). ``synthetic=None`` -> use the pcap dataset if it
    yields anything, else fall back to synthetic."""
    if synthetic is not True:
        x, y = pcap_table()
        if x and synthetic is not True:
            return x, y, "pcap-dataset"
        if synthetic is False:
            return x, y, "pcap-dataset"
    x, y = synthetic_table(n_per_class, seed=seed)
    return x, y, "synthetic-bootstrap"


def rows_to_matrix(rows: list[FeatureRow]) -> list[list[float]]:
    """Feature dicts -> a dense matrix in the fixed ``FEATURE_NAMES`` order."""
    return [[float(r.get(name, 0.0)) for name in FEATURE_NAMES] for r in rows]
